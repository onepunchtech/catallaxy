pub fn k3d_host_endpoint() -> &'static str {
    "host.k3d.internal"
}

pub fn generate_registries_yaml(port: u16, upstreams: &[String]) -> String {
    let host = k3d_host_endpoint();
    let mut body = String::from("mirrors:\n");
    for h in upstreams {
        body.push_str(&format!(
            "  {h}:\n    endpoint: [\"http://{host}:{port}\"]\n"
        ));
    }
    body
}

